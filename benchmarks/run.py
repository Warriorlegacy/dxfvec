#!/usr/bin/env python3
"""benchmarks/run.py — reproducible conversion benchmark for dxfvec.

WHY THIS EXISTS
---------------
Every performance number in a README must be regenerated by a script that
lives in the repository. Otherwise the number is decoration.

This script measures end-to-end conversion time, entity counts and output
sizes across a matrix of image sizes and engines, then writes
`benchmarks/results.json`. Commit that file alongside this script.

The numbers are produced by YOUR machine. They are not a claim about
performance in general; they are a reproducible baseline that anyone can
verify by running this file.

USAGE
-----
    python benchmarks/run.py                 # default matrix
    python benchmarks/run.py --quick         # single size, for CI smoke
    python benchmarks/run.py --repeats 5     # more stable medians

OUTPUT
------
    benchmarks/results.json   (committed)
    benchmarks/inputs/*.png   (generated, gitignored)

Requires: the package's normal dependencies. No API keys, no network.
"""

from __future__ import annotations

import argparse
import json
import platform
import statistics
import sys
import tempfile
import time
from datetime import datetime, timezone
from pathlib import Path

# Allow running from a repo checkout without installing the package.
REPO_ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(REPO_ROOT / "src"))

try:
    from PIL import Image, ImageDraw
except ImportError:
    sys.exit("Pillow is required: pip install Pillow")

from dxfvec import ClassicEngine, AdvancedEngine  # noqa: E402

# --------------------------------------------------------------------------
# Test input generation
# --------------------------------------------------------------------------
# Synthetic drawings with known geometry. We generate them rather than ship
# binary fixtures so the inputs are inspectable and diffable in review.

SIZES = {
    "small_512": 512,
    "medium_1024": 1024,
    "large_2048": 2048,
}


def generate_technical_drawing(path: Path, size: int) -> None:
    """Draw a bracket-like technical drawing: lines, circles, arcs.

    Deliberately mixed geometry — straight edges exercise the polyline path,
    circles exercise arc detection, and a rotated rect exercises the
    perspective/deskew code.
    """
    img = Image.new("L", (size, size), color=255)
    d = ImageDraw.Draw(img)
    s = size / 512.0  # scale all coordinates from a 512 reference

    lw = max(1, int(2 * s))
    ink = 0  # black on white

    # Outer plate
    d.rectangle([60 * s, 60 * s, 452 * s, 452 * s], outline=ink, width=lw)
    # Inner cutout
    d.rectangle([140 * s, 140 * s, 372 * s, 372 * s], outline=ink, width=lw)

    # Mounting holes — exercise circle/arc detection
    for cx, cy in [(100, 100), (412, 100), (100, 412), (412, 412)]:
        r = 22 * s
        d.ellipse([cx * s - r, cy * s - r, cx * s + r, cy * s + r],
                  outline=ink, width=lw)

    # Large bore through the middle
    r = 60 * s
    d.ellipse([256 * s - r, 256 * s - r, 256 * s + r, 256 * s + r],
              outline=ink, width=lw)

    # Slot features — long thin closed shapes
    d.rounded_rectangle([180 * s, 240 * s, 332 * s, 272 * s],
                        radius=16 * s, outline=ink, width=lw)

    # Diagonal rib
    d.line([80 * s, 440 * s, 440 * s, 80 * s], fill=ink, width=lw)

    # Dimension marks (short straight segments)
    for y in (150, 200, 300, 350):
        d.line([470 * s, y * s, 500 * s, y * s], fill=ink, width=lw)

    img.save(path)


# --------------------------------------------------------------------------
# Timing harness
# --------------------------------------------------------------------------

def time_conversion(engine, image_path: Path, out_dir: Path,
                    config: dict, repeats: int) -> dict:
    """Run one engine over one image `repeats` times; return timing stats."""
    times: list[float] = []
    last_result: dict = {}

    for _ in range(repeats):
        # Fresh output dir per run so file writes are not cached.
        run_dir = Path(tempfile.mkdtemp(dir=out_dir))
        t0 = time.perf_counter()
        result = engine.convert(str(image_path), run_dir, dict(config))
        t1 = time.perf_counter()
        times.append(t1 - t0)
        last_result = result or {}

    def stat(fn):
        return round(fn(times), 4)

    return {
        "repeats": repeats,
        "median_s": stat(statistics.median),
        "min_s": stat(min),
        "max_s": stat(max),
        "stdev_s": stat(statistics.stdev) if len(times) > 1 else 0.0,
        # Whatever the engine reports back; keys vary, so we pass it through
        # and let the results file document what is actually available.
        "engine_reported": {
            k: v for k, v in last_result.items()
            if isinstance(v, (int, float, str, bool))
        },
    }


def measure_input(image_path: Path) -> dict:
    with Image.open(image_path) as im:
        return {
            "width": im.width,
            "height": im.height,
            "bytes": image_path.stat().st_size,
        }


# --------------------------------------------------------------------------
# Main
# --------------------------------------------------------------------------

def main() -> int:
    ap = argparse.ArgumentParser(description="dxfvec conversion benchmark")
    ap.add_argument("--quick", action="store_true",
                    help="single size, fewer repeats (for CI)")
    ap.add_argument("--repeats", type=int, default=3,
                    help="timed runs per configuration (default 3)")
    ap.add_argument("--engines", default="classic,advanced",
                    help="comma-separated engine names")
    args = ap.parse_args()

    out_root = REPO_ROOT / "benchmarks"
    inputs_dir = out_root / "inputs"
    work_dir = out_root / ".work"
    inputs_dir.mkdir(parents=True, exist_ok=True)
    work_dir.mkdir(parents=True, exist_ok=True)

    sizes = {"medium_1024": 1024} if args.quick else SIZES
    repeats = 1 if args.quick else args.repeats

    available = {"classic": ClassicEngine(), "advanced": AdvancedEngine()}
    wanted = [e.strip() for e in args.engines.split(",") if e.strip()]
    engines = {k: available[k] for k in wanted if k in available}

    if not engines:
        print(f"No valid engines in {wanted}; have {list(available)}",
              file=sys.stderr)
        return 2

    # --- generate inputs ---
    images: dict[str, Path] = {}
    for label, size in sizes.items():
        p = inputs_dir / f"{label}.png"
        generate_technical_drawing(p, size)
        images[label] = p

    print(f"dxfvec conversion benchmark")
    print(f"  platform : {platform.system()} {platform.release()}")
    print(f"  python   : {platform.python_version()}")
    print(f"  engines  : {', '.join(engines)}")
    print(f"  repeats  : {repeats}")
    print()

    results: dict = {
        "schema_version": 1,
        "generated_at": datetime.now(timezone.utc).isoformat(timespec="seconds"),
        "environment": {
            "platform": f"{platform.system()} {platform.release()}",
            "machine": platform.machine(),
            "python": platform.python_version(),
            "processor": platform.processor() or "unknown",
        },
        "method": {
            "description": (
                "End-to-end engine.convert() wall time on synthetic technical "
                "drawings generated by benchmarks/run.py. Included in the "
                "measurement: preprocessing, contour tracing, arc detection, "
                "DXF write and QA report. Excluded: process start-up."
            ),
            "timing": "time.perf_counter()",
            "aggregation": "median of N runs",
            "repeats": repeats,
            "caveat": (
                "Single-machine measurement on the author's hardware. Not a "
                "claim about absolute performance elsewhere. Re-run to verify."
            ),
        },
        "inputs": {},
        "results": [],
    }

    for label, path in images.items():
        results["inputs"][label] = measure_input(path)
        print(f"input {label}: {results['inputs'][label]['width']}px")

    print()
    header = f"{'engine':10s} {'input':14s} {'median':>9s} {'min':>9s} {'max':>9s} {'std':>8s}"
    print(header)
    print("-" * len(header))

    for eng_name, engine in engines.items():
        for label, path in images.items():
            try:
                stats = time_conversion(engine, path, work_dir, {}, repeats)
            except Exception as exc:  # noqa: BLE001 — benchmark must not abort
                print(f"{eng_name:10s} {label:14s} FAILED: {type(exc).__name__}: {exc}")
                results["results"].append({
                    "engine": eng_name,
                    "input": label,
                    "error": f"{type(exc).__name__}: {exc}",
                })
                continue

            print(f"{eng_name:10s} {label:14s} "
                  f"{stats['median_s']:8.4f}s {stats['min_s']:8.4f}s "
                  f"{stats['max_s']:8.4f}s {stats['stdev_s']:7.4f}s")

            results["results"].append({
                "engine": eng_name,
                "input": label,
                **stats,
            })

    # --- derived summary: scaling behaviour ---
    # Useful for the README: does time scale linearly with pixel count?
    for eng_name in engines:
        rows = [r for r in results["results"]
                if r.get("engine") == eng_name and "median_s" in r]
        if len(rows) >= 2:
            rows_sorted = sorted(
                rows, key=lambda r: results["inputs"][r["input"]]["width"])
            first, last = rows_sorted[0], rows_sorted[-1]
            px_first = (results["inputs"][first["input"]]["width"] ** 2)
            px_last = (results["inputs"][last["input"]]["width"] ** 2)
            if first["median_s"] > 0:
                pixel_ratio = px_last / px_first
                time_ratio = last["median_s"] / first["median_s"]
                results.setdefault("scaling", {})[eng_name] = {
                    "from": first["input"],
                    "to": last["input"],
                    "pixel_ratio": round(pixel_ratio, 1),
                    "time_ratio": round(time_ratio, 2),
                    "note": (
                        "time_ratio < pixel_ratio indicates sub-quadratic "
                        "scaling on this input range"
                    ),
                }

    out_file = out_root / "results.json"
    out_file.write_text(json.dumps(results, indent=2) + "\n", encoding="utf-8")

    print()
    print(f"written: {out_file.relative_to(REPO_ROOT)}")
    if "scaling" in results:
        print()
        print("scaling:")
        for eng, s in results["scaling"].items():
            print(f"  {eng:10s} {s['from']} -> {s['to']}: "
                  f"{s['pixel_ratio']}x pixels, {s['time_ratio']}x time")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
